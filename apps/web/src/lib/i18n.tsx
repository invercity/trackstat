export type TKey = keyof (typeof dict)['uk'];

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  dName: (d?: Pick<Discipline, 'name' | 'nameEn'> | null) => string;
}
const I18n = createContext<Ctx>(null as unknown as Ctx);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('uk');
  useEffect(() => {
    const saved = localStorage.getItem('lang');
    if (saved === 'en' || saved === 'uk') setLangState(saved);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('lang', l);
    document.documentElement.lang = l;
  };
  const t = useCallback((key: string) => (dict[lang] as Record<string, string>)[key] ?? key, [lang]);
  const dName = useCallback((d?: Pick<Discipline, 'name' | 'nameEn'> | null) => (d ? (lang === 'en' ? d.nameEn : d.name) : ''), [lang]);
  return <I18n.Provider value={{ lang, setLang, t, dName }}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
